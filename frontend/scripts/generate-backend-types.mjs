// Regenerate from a running API, or deterministically from the checked-in snapshot.
// BACKEND_URL and the optional service secret remain in this Node process.
import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const schemaPath = new URL('../src/server/backend/openapi.json', import.meta.url);
let schema;
if (process.argv.includes('--snapshot')) {
  schema = JSON.parse(await readFile(schemaPath, 'utf8'));
} else {
  if (!process.env.BACKEND_URL) throw new Error('Set BACKEND_URL, or pass --snapshot to use the recorded schema.');
  const response = await fetch(new URL('/openapi.json', process.env.BACKEND_URL), {
    headers: process.env.BACKEND_SERVICE_SECRET ? { authorization: `Bearer ${process.env.BACKEND_SERVICE_SECRET}` } : {},
    redirect: 'error',
  });
  if (!response.ok) throw new Error(`OpenAPI fetch failed (${response.status}).`);
  schema = await response.json();
  await writeFile(schemaPath, JSON.stringify(schema, null, 2) + '\n');
}
const types = astToString(await openapiTS(schema));
await writeFile(new URL('../src/server/backend/schema.d.ts', import.meta.url), '// Generated by pnpm backend:types. Do not edit.\n' + types);
console.log('Backend types regenerated. Run pnpm typecheck.');
